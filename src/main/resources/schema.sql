-- Script de creación de la base de datos (H2 en memoria).
-- Spring Boot lo ejecuta al arrancar y Hibernate valida que coincida con las entidades (ddl-auto=validate).
-- Los DROP iniciales hacen que el script se pueda ejecutar más de una vez sobre la misma base.

DROP TABLE IF EXISTS PHONES;
DROP TABLE IF EXISTS USERAPI;

CREATE TABLE USERAPI (
    id_user    VARCHAR(36)   NOT NULL,
    name       VARCHAR(300)  NOT NULL,
    email      VARCHAR(100)  NOT NULL,
    password   VARCHAR(100)  NOT NULL,
    created    TIMESTAMP,
    modified   TIMESTAMP,
    last_login TIMESTAMP,
    token      VARCHAR(1000),
    is_active  BOOLEAN,
    CONSTRAINT pk_userapi PRIMARY KEY (id_user),
    CONSTRAINT uk_userapi_email UNIQUE (email)
);

CREATE TABLE PHONES (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    number       VARCHAR(20) NOT NULL,
    city_code    VARCHAR(10),
    country_code VARCHAR(10),
    id_user      VARCHAR(36) NOT NULL,
    CONSTRAINT pk_phones PRIMARY KEY (id),
    CONSTRAINT fk_phones_user FOREIGN KEY (id_user) REFERENCES USERAPI (id_user)
);

CREATE INDEX idx_phones_id_user ON PHONES (id_user);